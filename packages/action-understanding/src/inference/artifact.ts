/**
 * FC-008 Sprint 4A — parsing the frozen model artifacts into validated types.
 *
 * PURE. No filesystem, no crypto, no network, no Python. This module turns
 * `unknown` JSON into strongly typed artifacts or refuses, and nothing downstream
 * is allowed to see the `unknown` form.
 *
 * Reading bytes and verifying SHA-256 lives in `artifact-source.ts` in the
 * Node-only `@futureclick/futurebench-dataset` package, not here, because
 * everything under this package's `src/` is required to be free of Node builtins
 * — an invariant `tests/isolation.test.ts` enforces by scanning every file. The
 * split is what lets this parser run wherever the runtime runs.
 *
 * WHAT "VALIDATED" MEANS HERE
 *
 * The artifacts are generated by the frozen Python trainer, so the risk is not a
 * hostile file — it is a DRIFTED one: a regenerated artifact whose feature order
 * shifted, whose class order was re-sorted, or whose calibration belongs to the
 * other model family. Every one of those produces a numerically plausible result
 * that is silently wrong, which is why identity is checked against an independent
 * reference rather than against the artifact's own self-description:
 *
 * - Head orders are compared to `FC008_MATRIX_*` in `support-matrix.ts`, which is
 *   maintained in TypeScript and was never produced by the trainer. An artifact
 *   that re-sorted its verbs alphabetically fails here instead of quietly mapping
 *   logit 0 onto a different verb.
 * - Class order is compared to the frozen support matrix class numbering.
 * - Shapes are compared to the declared `shape` field AND to the frozen counts, so
 *   an artifact cannot declare a shape that matches its own wrong data.
 * - Every coefficient and intercept must be finite. A single NaN in a 13x370
 *   matrix would otherwise surface as a NaN probability much later, in a metric.
 *
 * Cross-family and cross-artifact checks live in `parseArtifactBundle`, because a
 * calibration artifact is only meaningful relative to the model it was fitted on.
 */

import { FC008_FEATURE_POLICY_VERSION } from "../feature-policy.js";
import { type Fc008ModelFamily, SHA256_HEX_REGEX } from "../hypothesis.js";
import {
  FC008_MATRIX_OBJECT_KIND_COUNT,
  FC008_MATRIX_OBJECT_KINDS,
  FC008_MATRIX_TRANSITION_PROPERTIES,
  FC008_MATRIX_TRANSITION_PROPERTY_COUNT,
  FC008_MATRIX_VERB_COUNT,
  FC008_MATRIX_VERBS,
  FC008_SUPPORT_MATRIX,
  FC008_SUPPORT_MATRIX_VERSION,
  FC008_SUPPORTED_TUPLE_COUNT,
} from "../support-matrix.js";

/** The frozen feature count. Not negotiable and not inferred from the file. */
export const FC008_FROZEN_FEATURE_COUNT = 370;

/** Artifact schema version this loader understands. */
export const FC008_ARTIFACT_SCHEMA_VERSION = "1.0";

/** Frozen class numbering, from the TypeScript support matrix. */
export const FC008_FROZEN_CLASS_ORDER: readonly number[] = Object.freeze(
  FC008_SUPPORT_MATRIX.map((entry) => entry.classNumber),
);

/**
 * Largest absolute coefficient accepted.
 *
 * Generous rather than tuned: the purpose is to catch a corrupt or exploded
 * artifact, not to express an opinion about regularization. The frozen models are
 * orders of magnitude below this.
 */
export const MAX_ABSOLUTE_COEFFICIENT = 1_000;

/** Why an artifact was refused. Categorical so a caller cannot widen it. */
export const ARTIFACT_LOAD_REFUSALS = Object.freeze([
  "not-an-object",
  "schema-version-unsupported",
  "model-family-unexpected",
  "field-missing",
  "field-type-invalid",
  "shape-mismatch",
  "feature-count-mismatch",
  "feature-order-mismatch",
  "class-order-mismatch",
  "head-order-mismatch",
  "head-missing",
  "non-finite-value",
  "coefficient-out-of-range",
  "identity-mismatch",
  "cross-family-artifact",
  "hash-mismatch",
  "temperature-invalid",
  "threshold-invalid",
] as const);
export type ArtifactLoadRefusal = (typeof ARTIFACT_LOAD_REFUSALS)[number];

/**
 * A refusal to load an artifact.
 *
 * Carries the categorical reason plus a bounded human path/detail. The reason is
 * what callers branch on; the detail exists so a drifted artifact is diagnosable
 * without reading the file by hand.
 */
export class ArtifactLoadError extends Error {
  readonly refusal: ArtifactLoadRefusal;
  readonly path: string;

  constructor(refusal: ArtifactLoadRefusal, path: string, detail: string) {
    super(`${refusal} at ${path}: ${detail}`);
    this.name = "ArtifactLoadError";
    this.refusal = refusal;
    this.path = path;
  }
}

function fail(refusal: ArtifactLoadRefusal, path: string, detail: string): never {
  throw new ArtifactLoadError(refusal, path, detail);
}

function asRecord(value: unknown, path: string): Record<string, unknown> {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    fail("not-an-object", path, "expected a JSON object");
  }
  return value as Record<string, unknown>;
}

function readRequiredString(source: Record<string, unknown>, key: string, path: string): string {
  const value = source[key];
  if (typeof value !== "string" || value.length === 0) {
    fail("field-missing", `${path}.${key}`, "expected a non-empty string");
  }
  return value;
}

function readSha256(source: Record<string, unknown>, key: string, path: string): string {
  const value = readRequiredString(source, key, path);
  if (!SHA256_HEX_REGEX.test(value)) {
    fail("field-type-invalid", `${path}.${key}`, "expected 64 lowercase hex characters");
  }
  return value;
}

function readDenseArray(value: unknown, path: string): readonly unknown[] {
  if (!Array.isArray(value)) {
    fail("field-type-invalid", path, "expected an array");
  }
  // A hole in a JSON-parsed array cannot normally occur, but an artifact handed
  // to us from another in-process producer could carry one, and `undefined * x`
  // is NaN rather than an error.
  for (let index = 0; index < value.length; index += 1) {
    if (!Object.hasOwn(value, index)) {
      fail("field-type-invalid", `${path}[${index}]`, "array must be dense");
    }
  }
  return value;
}

function readFiniteVector(value: unknown, expected: number, path: string): readonly number[] {
  const raw = readDenseArray(value, path);
  if (raw.length !== expected) {
    fail("shape-mismatch", path, `expected exactly ${expected} values, received ${raw.length}`);
  }
  const out: number[] = [];
  for (let index = 0; index < raw.length; index += 1) {
    const entry = raw[index];
    if (typeof entry !== "number" || !Number.isFinite(entry)) {
      fail(
        "non-finite-value",
        `${path}[${index}]`,
        `expected a finite number, received ${String(entry)}`,
      );
    }
    if (Math.abs(entry) > MAX_ABSOLUTE_COEFFICIENT) {
      fail(
        "coefficient-out-of-range",
        `${path}[${index}]`,
        `magnitude ${Math.abs(entry)} exceeds ${MAX_ABSOLUTE_COEFFICIENT}`,
      );
    }
    out.push(entry);
  }
  return Object.freeze(out);
}

function readFiniteMatrix(
  value: unknown,
  rows: number,
  columns: number,
  path: string,
): readonly (readonly number[])[] {
  const raw = readDenseArray(value, path);
  if (raw.length !== rows) {
    fail("shape-mismatch", path, `expected exactly ${rows} rows, received ${raw.length}`);
  }
  const out: (readonly number[])[] = [];
  for (let index = 0; index < raw.length; index += 1) {
    out.push(readFiniteVector(raw[index], columns, `${path}[${index}]`));
  }
  return Object.freeze(out);
}

/** The declared `shape` field must agree with the frozen dimensions. */
function assertDeclaredShape(declared: unknown, expected: readonly number[], path: string): void {
  const raw = readDenseArray(declared, path);
  if (raw.length !== expected.length || raw.some((value, index) => value !== expected[index])) {
    fail(
      "shape-mismatch",
      path,
      `declared shape ${JSON.stringify(raw)} does not equal the frozen ${JSON.stringify(expected)}`,
    );
  }
}

function assertExactStringOrder(
  value: unknown,
  expected: readonly string[],
  refusal: ArtifactLoadRefusal,
  path: string,
): readonly string[] {
  const raw = readDenseArray(value, path);
  if (raw.length !== expected.length) {
    fail(refusal, path, `expected ${expected.length} entries, received ${raw.length}`);
  }
  for (let index = 0; index < expected.length; index += 1) {
    if (raw[index] !== expected[index]) {
      fail(
        refusal,
        `${path}[${index}]`,
        `expected ${JSON.stringify(expected[index])}, received ${JSON.stringify(raw[index])}`,
      );
    }
  }
  return Object.freeze(expected.slice());
}

function assertFrozenClassOrder(value: unknown, path: string): readonly number[] {
  const raw = readDenseArray(value, path);
  if (raw.length !== FC008_SUPPORTED_TUPLE_COUNT) {
    fail(
      "class-order-mismatch",
      path,
      `expected ${FC008_SUPPORTED_TUPLE_COUNT} class numbers, received ${raw.length}`,
    );
  }
  for (let index = 0; index < FC008_FROZEN_CLASS_ORDER.length; index += 1) {
    if (raw[index] !== FC008_FROZEN_CLASS_ORDER[index]) {
      fail(
        "class-order-mismatch",
        `${path}[${index}]`,
        `expected class ${FC008_FROZEN_CLASS_ORDER[index]}, received ${String(raw[index])}`,
      );
    }
  }
  return Object.freeze(FC008_FROZEN_CLASS_ORDER.slice());
}

/**
 * Identities every frozen artifact repeats.
 *
 * Parsed as a unit so the bundle check can compare them across the triplet
 * without each parser growing its own copy of the comparison.
 */
export interface ArtifactSharedIdentity {
  readonly datasetHash: string;
  readonly vocabularyHash: string;
  readonly supportMatrixVersion: string;
  readonly featurePolicyVersion: string;
}

function readSharedIdentity(source: Record<string, unknown>, path: string): ArtifactSharedIdentity {
  const supportMatrixVersion = readRequiredString(source, "supportMatrixVersion", path);
  const featurePolicyVersion = readRequiredString(source, "featurePolicyVersion", path);
  // Compared to the TypeScript constants, not merely to each other: an artifact
  // built under a different support matrix would otherwise be self-consistent.
  if (supportMatrixVersion !== FC008_SUPPORT_MATRIX_VERSION) {
    fail(
      "identity-mismatch",
      `${path}.supportMatrixVersion`,
      `expected ${FC008_SUPPORT_MATRIX_VERSION}, received ${supportMatrixVersion}`,
    );
  }
  if (featurePolicyVersion !== FC008_FEATURE_POLICY_VERSION) {
    fail(
      "identity-mismatch",
      `${path}.featurePolicyVersion`,
      `expected ${FC008_FEATURE_POLICY_VERSION}, received ${featurePolicyVersion}`,
    );
  }
  return Object.freeze({
    datasetHash: readSha256(source, "datasetHash", path),
    vocabularyHash: readSha256(source, "vocabularyHash", path),
    supportMatrixVersion,
    featurePolicyVersion,
  });
}

function assertSchemaAndFamily(
  source: Record<string, unknown>,
  expectedFamily: Fc008ModelFamily,
  path: string,
): void {
  const schemaVersion = readRequiredString(source, "schemaVersion", path);
  if (schemaVersion !== FC008_ARTIFACT_SCHEMA_VERSION) {
    fail(
      "schema-version-unsupported",
      `${path}.schemaVersion`,
      `expected ${FC008_ARTIFACT_SCHEMA_VERSION}, received ${schemaVersion}`,
    );
  }
  const modelFamily = readRequiredString(source, "modelFamily", path);
  if (modelFamily !== expectedFamily) {
    fail(
      "model-family-unexpected",
      `${path}.modelFamily`,
      `expected ${expectedFamily}, received ${modelFamily}`,
    );
  }
}

