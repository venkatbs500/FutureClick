export interface JointModelArtifact {
  readonly modelFamily: "joint-logistic";
  readonly modelVersion: string;
  readonly schemaVersion: string;
  readonly identity: ArtifactSharedIdentity;
  /** Frozen class numbering, 1..13. */
  readonly classOrder: readonly number[];
  /** The frozen 370-feature order, exactly as fitted. */
  readonly featureOrder: readonly string[];
  /** 13 x 370. Row `k` is the weight vector for `classOrder[k]`. */
  readonly coefficients: readonly (readonly number[])[];
  /** 13 intercepts, aligned to `classOrder`. */
  readonly intercepts: readonly number[];
}

export interface FactorizedHead {
  readonly name: "verb" | "objectKind" | "transitionProperty";
  readonly classOrder: readonly string[];
  readonly coefficients: readonly (readonly number[])[];
  readonly intercepts: readonly number[];
}

/** Which head index each supported tuple draws from. */
export interface ClassHeadIndices {
  readonly classNumber: number;
  readonly verbIndex: number;
  readonly objectIndex: number;
  readonly transitionPropertyIndex: number;
}

export interface FactorizedModelArtifact {
  readonly modelFamily: "factorized-logistic";
  readonly modelVersion: string;
  readonly schemaVersion: string;
  readonly identity: ArtifactSharedIdentity;
  readonly classOrder: readonly number[];
  readonly featureOrder: readonly string[];
  readonly verb: FactorizedHead;
  readonly objectKind: FactorizedHead;
  readonly transitionProperty: FactorizedHead;
  /** Composition mapping, aligned to `classOrder`. */
  readonly classHeadIndices: readonly ClassHeadIndices[];
  readonly compositionVersion: string;
}

export type ModelArtifact = JointModelArtifact | FactorizedModelArtifact;

function readFeatureOrder(source: Record<string, unknown>, path: string): readonly string[] {
  const raw = readDenseArray(source.featureOrder, `${path}.featureOrder`);
  if (raw.length !== FC008_FROZEN_FEATURE_COUNT) {
    fail(
      "feature-count-mismatch",
      `${path}.featureOrder`,
      `expected ${FC008_FROZEN_FEATURE_COUNT} features, received ${raw.length}`,
    );
  }
  const seen = new Set<string>();
  const out: string[] = [];
  for (let index = 0; index < raw.length; index += 1) {
    const name = raw[index];
    if (typeof name !== "string" || name.length === 0) {
      fail("field-type-invalid", `${path}.featureOrder[${index}]`, "expected a non-empty string");
    }
    // A duplicate name would make the order ambiguous: two different indices
    // would claim the same feature, and a caller mapping by name would pick one
    // arbitrarily.
    if (seen.has(name)) {
      fail("feature-order-mismatch", `${path}.featureOrder[${index}]`, `duplicate feature ${name}`);
    }
    seen.add(name);
    out.push(name);
  }
  return Object.freeze(out);
}

export function parseJointModelArtifact(input: unknown, path = "jointModel"): JointModelArtifact {
  const source = asRecord(input, path);
  assertSchemaAndFamily(source, "joint-logistic", path);

  const shape = asRecord(source.shape, `${path}.shape`);
  assertDeclaredShape(
    shape.coefficients,
    [FC008_SUPPORTED_TUPLE_COUNT, FC008_FROZEN_FEATURE_COUNT],
    `${path}.shape.coefficients`,
  );
  assertDeclaredShape(shape.intercepts, [FC008_SUPPORTED_TUPLE_COUNT], `${path}.shape.intercepts`);

  return Object.freeze({
    modelFamily: "joint-logistic" as const,
    modelVersion: readRequiredString(source, "modelVersion", path),
    schemaVersion: FC008_ARTIFACT_SCHEMA_VERSION,
    identity: readSharedIdentity(source, path),
    classOrder: assertFrozenClassOrder(source.classOrder, `${path}.classOrder`),
    featureOrder: readFeatureOrder(source, path),
    coefficients: readFiniteMatrix(
      source.coefficients,
      FC008_SUPPORTED_TUPLE_COUNT,
      FC008_FROZEN_FEATURE_COUNT,
      `${path}.coefficients`,
    ),
    intercepts: readFiniteVector(
      source.intercepts,
      FC008_SUPPORTED_TUPLE_COUNT,
      `${path}.intercepts`,
    ),
  });
}

const HEAD_SPECIFICATIONS = Object.freeze([
  { name: "verb" as const, order: FC008_MATRIX_VERBS, count: FC008_MATRIX_VERB_COUNT },
  {
    name: "objectKind" as const,
    order: FC008_MATRIX_OBJECT_KINDS,
    count: FC008_MATRIX_OBJECT_KIND_COUNT,
  },
  {
    name: "transitionProperty" as const,
    order: FC008_MATRIX_TRANSITION_PROPERTIES,
    count: FC008_MATRIX_TRANSITION_PROPERTY_COUNT,
  },
]);

function parseHead(
  heads: Record<string, unknown>,
  specification: (typeof HEAD_SPECIFICATIONS)[number],
  path: string,
): FactorizedHead {
  const { name, order, count } = specification;
  if (!Object.hasOwn(heads, name)) {
    fail("head-missing", `${path}.${name}`, "frozen head is absent");
  }
  const head = asRecord(heads[name], `${path}.${name}`);
  // A head declares one flat coefficient shape, unlike the joint artifact which
  // declares coefficients and intercepts separately.
  assertDeclaredShape(head.shape, [count, FC008_FROZEN_FEATURE_COUNT], `${path}.${name}.shape`);

  return Object.freeze({
    name,
    classOrder: assertExactStringOrder(
      head.classOrder,
      order as readonly string[],
      "head-order-mismatch",
      `${path}.${name}.classOrder`,
    ),
    coefficients: readFiniteMatrix(
      head.coefficients,
      count,
      FC008_FROZEN_FEATURE_COUNT,
      `${path}.${name}.coefficients`,
    ),
    intercepts: readFiniteVector(head.intercepts, count, `${path}.${name}.intercepts`),
  });
}

function parseClassHeadIndices(input: unknown, path: string): readonly ClassHeadIndices[] {
  const raw = readDenseArray(input, path);
  if (raw.length !== FC008_SUPPORTED_TUPLE_COUNT) {
    fail(
      "shape-mismatch",
      path,
      `expected ${FC008_SUPPORTED_TUPLE_COUNT} entries, received ${raw.length}`,
    );
  }
  const out: ClassHeadIndices[] = [];
  for (let index = 0; index < raw.length; index += 1) {
    const entry = asRecord(raw[index], `${path}[${index}]`);
    const readIndex = (key: string, bound: number): number => {
      const value = entry[key];
      if (typeof value !== "number" || !Number.isInteger(value) || value < 0 || value >= bound) {
        fail(
          "field-type-invalid",
          `${path}[${index}].${key}`,
          `expected an integer in [0, ${bound}), received ${String(value)}`,
        );
      }
      return value;
    };
    const classNumber = entry.classNumber;
    // Composition is positional: entry `i` must describe `classOrder[i]`, or the
    // composed logit vector would be a permutation of the intended one.
    if (classNumber !== FC008_FROZEN_CLASS_ORDER[index]) {
      fail(
        "class-order-mismatch",
        `${path}[${index}].classNumber`,
        `expected ${FC008_FROZEN_CLASS_ORDER[index]}, received ${String(classNumber)}`,
      );
    }
    out.push(
      Object.freeze({
        classNumber: FC008_FROZEN_CLASS_ORDER[index] as number,
        verbIndex: readIndex("verbIndex", FC008_MATRIX_VERB_COUNT),
        objectIndex: readIndex("objectIndex", FC008_MATRIX_OBJECT_KIND_COUNT),
        transitionPropertyIndex: readIndex(
          "transitionPropertyIndex",
          FC008_MATRIX_TRANSITION_PROPERTY_COUNT,
        ),
      }),
    );
  }
  return Object.freeze(out);
}

export function parseFactorizedModelArtifact(
  input: unknown,
  path = "factorizedModel",
): FactorizedModelArtifact {
  const source = asRecord(input, path);
  assertSchemaAndFamily(source, "factorized-logistic", path);

  const heads = asRecord(source.heads, `${path}.heads`);
  const composition = asRecord(source.composition, `${path}.composition`);
  if (composition.learnedCombiner !== false) {
    fail(
      "identity-mismatch",
      `${path}.composition.learnedCombiner`,
      "frozen composition is additive with no learned combiner",
    );
  }

  const [verbSpec, objectSpec, propertySpec] = HEAD_SPECIFICATIONS;
  return Object.freeze({
    modelFamily: "factorized-logistic" as const,
    modelVersion: readRequiredString(source, "modelVersion", path),
    schemaVersion: FC008_ARTIFACT_SCHEMA_VERSION,
    identity: readSharedIdentity(source, path),
    classOrder: assertFrozenClassOrder(source.classOrder, `${path}.classOrder`),
    featureOrder: readFeatureOrder(source, path),
    verb: parseHead(heads, verbSpec as (typeof HEAD_SPECIFICATIONS)[number], `${path}.heads`),
    objectKind: parseHead(
      heads,
      objectSpec as (typeof HEAD_SPECIFICATIONS)[number],
      `${path}.heads`,
    ),
    transitionProperty: parseHead(
      heads,
      propertySpec as (typeof HEAD_SPECIFICATIONS)[number],
      `${path}.heads`,
    ),
    classHeadIndices: parseClassHeadIndices(
      composition.classOrderHeadIndices,
      `${path}.composition.classOrderHeadIndices`,
    ),
    compositionVersion: readRequiredString(
      composition,
      "compositionVersion",
      `${path}.composition`,
    ),
  });
}

