export interface CalibrationArtifact {
  readonly modelFamily: Fc008ModelFamily;
  readonly modelVersion: string;
  readonly calibrationArtifactVersion: string;
  readonly identity: ArtifactSharedIdentity;
  /** SHA-256 of the model artifact this temperature was fitted against. */
  readonly modelArtifactSha256: string;
  /** Frozen temperature. Strictly positive. */
  readonly temperature: number;
}

export function parseCalibrationArtifact(
  input: unknown,
  expectedFamily: Fc008ModelFamily,
  path = "calibration",
): CalibrationArtifact {
  const source = asRecord(input, path);
  assertSchemaAndFamily(source, expectedFamily, path);
  const fit = asRecord(source.temperatureFit, `${path}.temperatureFit`);
  const temperature = fit.temperature;
  if (typeof temperature !== "number" || !Number.isFinite(temperature) || temperature <= 0) {
    fail(
      "temperature-invalid",
      `${path}.temperatureFit.temperature`,
      `expected a finite positive number, received ${String(temperature)}`,
    );
  }
  return Object.freeze({
    modelFamily: expectedFamily,
    modelVersion: readRequiredString(source, "modelVersion", path),
    calibrationArtifactVersion: readRequiredString(source, "calibrationArtifactVersion", path),
    identity: readSharedIdentity(source, path),
    modelArtifactSha256: readSha256(source, "modelArtifactSha256", path),
    temperature,
  });
}

export interface PolicyArtifact {
  readonly modelFamily: Fc008ModelFamily;
  readonly modelVersion: string;
  readonly abstentionPolicyVersion: string;
  readonly calibrationArtifactVersion: string;
  readonly identity: ArtifactSharedIdentity;
  readonly modelArtifactSha256: string;
  readonly calibrationArtifactSha256: string;
  /** Frozen acceptance threshold on calibrated confidence, within [0, 1]. */
  readonly selectedConfidenceThreshold: number;
  /** Whether threshold selection fell back. Reported, never acted on here. */
  readonly fallbackUsed: boolean;
}

export function parsePolicyArtifact(
  input: unknown,
  expectedFamily: Fc008ModelFamily,
  path = "policy",
): PolicyArtifact {
  const source = asRecord(input, path);
  assertSchemaAndFamily(source, expectedFamily, path);
  const threshold = source.selectedConfidenceThreshold;
  if (
    typeof threshold !== "number" ||
    !Number.isFinite(threshold) ||
    threshold < 0 ||
    threshold > 1
  ) {
    fail(
      "threshold-invalid",
      `${path}.selectedConfidenceThreshold`,
      `expected a finite number within [0, 1], received ${String(threshold)}`,
    );
  }
  const fallbackUsed = source.fallbackUsed;
  if (typeof fallbackUsed !== "boolean") {
    fail("field-type-invalid", `${path}.fallbackUsed`, "expected a boolean");
  }
  return Object.freeze({
    modelFamily: expectedFamily,
    modelVersion: readRequiredString(source, "modelVersion", path),
    abstentionPolicyVersion: readRequiredString(source, "abstentionPolicyVersion", path),
    calibrationArtifactVersion: readRequiredString(source, "calibrationArtifactVersion", path),
    identity: readSharedIdentity(source, path),
    modelArtifactSha256: readSha256(source, "modelArtifactSha256", path),
    calibrationArtifactSha256: readSha256(source, "calibrationArtifactSha256", path),
    selectedConfidenceThreshold: threshold,
    fallbackUsed,
  });
}

// ============================================================================
// BUNDLE: THE TRIPLET, CHECKED AS A UNIT
// ============================================================================

/**
 * One family's validated model, calibration, and policy, proven to belong together.
 *
 * The hashes are supplied by the caller that read the bytes, because this module
 * does no hashing. They are then checked against the cross-references inside the
 * artifact bodies, which is what makes a cross-family or re-fitted calibration
 * impossible to pair with the wrong model.
 */
export interface ArtifactBundle<TModel extends ModelArtifact = ModelArtifact> {
  readonly modelFamily: Fc008ModelFamily;
  readonly model: TModel;
  readonly calibration: CalibrationArtifact;
  readonly policy: PolicyArtifact;
  readonly modelSha256: string;
  readonly calibrationSha256: string;
  readonly policySha256: string;
}

export interface ArtifactBundleInput {
  readonly modelFamily: Fc008ModelFamily;
  readonly model: unknown;
  readonly calibration: unknown;
  readonly policy: unknown;
  readonly modelSha256: string;
  readonly calibrationSha256: string;
  readonly policySha256: string;
}

export function parseArtifactBundle(input: ArtifactBundleInput): ArtifactBundle {
  const { modelFamily } = input;
  const model =
    modelFamily === "joint-logistic"
      ? parseJointModelArtifact(input.model, `${modelFamily}.model`)
      : parseFactorizedModelArtifact(input.model, `${modelFamily}.model`);
  const calibration = parseCalibrationArtifact(
    input.calibration,
    modelFamily,
    `${modelFamily}.calibration`,
  );
  const policy = parsePolicyArtifact(input.policy, modelFamily, `${modelFamily}.policy`);

  // Content-linked, not filename-linked. The calibration must name the exact
  // model bytes it was fitted on, and the policy must name both. This is what
  // rejects a factorized calibration handed in beside a joint model even when
  // every file is individually valid.
  if (calibration.modelArtifactSha256 !== input.modelSha256) {
    fail(
      "cross-family-artifact",
      `${modelFamily}.calibration.modelArtifactSha256`,
      `references model ${calibration.modelArtifactSha256}, but the supplied model hashes to ${input.modelSha256}`,
    );
  }
  if (policy.modelArtifactSha256 !== input.modelSha256) {
    fail(
      "cross-family-artifact",
      `${modelFamily}.policy.modelArtifactSha256`,
      `references model ${policy.modelArtifactSha256}, but the supplied model hashes to ${input.modelSha256}`,
    );
  }
  if (policy.calibrationArtifactSha256 !== input.calibrationSha256) {
    fail(
      "cross-family-artifact",
      `${modelFamily}.policy.calibrationArtifactSha256`,
      `references calibration ${policy.calibrationArtifactSha256}, but the supplied calibration hashes to ${input.calibrationSha256}`,
    );
  }

  // Versions must agree where two artifacts both carry the same one.
  if (calibration.modelVersion !== model.modelVersion) {
    fail(
      "identity-mismatch",
      `${modelFamily}.calibration.modelVersion`,
      `expected ${model.modelVersion}, received ${calibration.modelVersion}`,
    );
  }
  if (policy.modelVersion !== model.modelVersion) {
    fail(
      "identity-mismatch",
      `${modelFamily}.policy.modelVersion`,
      `expected ${model.modelVersion}, received ${policy.modelVersion}`,
    );
  }
  if (policy.calibrationArtifactVersion !== calibration.calibrationArtifactVersion) {
    fail(
      "identity-mismatch",
      `${modelFamily}.policy.calibrationArtifactVersion`,
      `expected ${calibration.calibrationArtifactVersion}, received ${policy.calibrationArtifactVersion}`,
    );
  }

  for (const key of [
    "datasetHash",
    "vocabularyHash",
    "supportMatrixVersion",
    "featurePolicyVersion",
  ] as const) {
    for (const [label, other] of [
      ["calibration", calibration.identity],
      ["policy", policy.identity],
    ] as const) {
      if (other[key] !== model.identity[key]) {
        fail(
          "identity-mismatch",
          `${modelFamily}.${label}.${key}`,
          `expected ${model.identity[key]}, received ${other[key]}`,
        );
      }
    }
  }

  return Object.freeze({
    modelFamily,
    model,
    calibration,
    policy,
    modelSha256: input.modelSha256,
    calibrationSha256: input.calibrationSha256,
    policySha256: input.policySha256,
  });
}

/**
 * Require the two families to share one feature order, byte for byte.
 *
 * RQ1 compares the families "trained on the same observations and privacy-safe
 * features". If their feature orders diverged, every comparison downstream would
 * be between models reading different inputs, and the frozen preregistration's
 * `sharedAcrossFamilies: true` claim would be false. Checked rather than assumed.
 */
export function assertSharedFeatureOrder(
  joint: JointModelArtifact,
  factorized: FactorizedModelArtifact,
): void {
  if (joint.featureOrder.length !== factorized.featureOrder.length) {
    fail(
      "feature-count-mismatch",
      "featureOrder",
      `joint has ${joint.featureOrder.length} features, factorized has ${factorized.featureOrder.length}`,
    );
  }
  for (let index = 0; index < joint.featureOrder.length; index += 1) {
    if (joint.featureOrder[index] !== factorized.featureOrder[index]) {
      fail(
        "feature-order-mismatch",
        `featureOrder[${index}]`,
        `joint has ${JSON.stringify(joint.featureOrder[index])}, factorized has ${JSON.stringify(factorized.featureOrder[index])}`,
      );
    }
  }
}
